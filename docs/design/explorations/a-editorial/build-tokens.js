// Writes tokens.css from tokens.json, so the prototype and contrast.js read one source of truth.
// Usage: node build-tokens.js
const fs = require('fs');
const path = require('path');
const tokens = require('./tokens.json');

const block = (vars) => Object.entries(vars).map(([k, v]) => `  --${k}: ${v};`).join('\n');
const css = `/* Generated by build-tokens.js from tokens.json. Edit the JSON, not this file. */
:root,
[data-theme="light"] {
  color-scheme: light;
${block(tokens.light)}
}

[data-theme="dark"] {
  color-scheme: dark;
${block(tokens.dark)}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;
${block(tokens.dark).replace(/^/gm, '  ')}
  }
}
`;
fs.writeFileSync(path.join(__dirname, 'tokens.css'), css);
console.log('tokens.css written');
