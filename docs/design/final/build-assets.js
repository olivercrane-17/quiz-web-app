// Builds sprite.js: one inline SVG sprite with the Lucide icons we use, our custom glyphs,
// the newt mark at three detail levels, and the QR code for the host lobby.
//   node build-assets.js /path/to/scratch/node_modules
// The scratch node_modules needs lucide-static@1.66.0 and qrcode-generator@2.0.4. Delete it afterwards;
// sprite.js is committed so the prototype opens with no install.
'use strict';
const fs = require('fs');
const path = require('path');
const { mark } = require('./mark.js');

const NM = process.argv[2];
if (!NM) throw new Error('pass the node_modules folder that holds lucide-static and qrcode-generator');

// Lucide (ISC). The id is "i-" plus the Lucide name, so code can switch to lucide-react one to one.
const LUCIDE = [
  'x', 'check', 'arrow-right', 'chevron-right', 'chevron-down', 'settings', 'volume-x', 'volume-2', 'timer',
  'share', 'snowflake', 'calendar-days', 'layers', 'users', 'user-round', 'chart-no-axes-column', 'flag',
  'book-open', 'target', 'search', 'heart', 'lock', 'lock-open', 'qr-code', 'user-plus', 'play', 'rotate-ccw',
  'wifi-off', 'info', 'triangle-alert', 'copy', 'link', 'ellipsis', 'pencil', 'user-x', 'shuffle', 'trophy',
  'swords', 'arrow-down-to-line', 'map-pin', 'user', 'film', 'monitor', 'smartphone', 'eye-off', 'clock', 'star',
  'delete', 'corner-down-left', 'plus', 'minus', 'globe', 'mic', 'arrow-big-up', 'smile', 'keyboard', 'ticket',
];
const iconDir = path.join(NM, 'lucide-static', 'icons');
const lucide = LUCIDE.map((name) => {
  const svg = fs.readFileSync(path.join(iconDir, name + '.svg'), 'utf8');
  const inner = svg.replace(/<!--[\s\S]*?-->/g, '').replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/\s*\n\s*/g, '');
  return `<symbol id="i-${name}" viewBox="0 0 24 24">${inner}</symbol>`;
});

// Custom glyphs drawn on Lucide's rules (24 px grid, 2 px stroke, round caps and joins)
const custom = [
  // The streak: four strokes and a gate. Counting days is what a streak is, so no flame.
  '<symbol id="i-tally" viewBox="0 0 24 24"><path d="M6.5 5v14M10.5 5v14M14.5 5v14M18.5 5v14"/><path d="M3.5 16.5l17.5-9"/></symbol>',
  // One new stroke, drawn when the streak grows (animated with stroke-dashoffset)
  '<symbol id="i-tally-stroke" viewBox="0 0 24 24"><path d="M3.5 16.5l17.5-9" pathLength="1"/></symbol>',
  // A wax-free rubber stamp outline, used behind "Not Mary Shelley" style marks
  '<symbol id="i-stamp-x" viewBox="0 0 24 24"><path d="M7 7l10 10M17 7L7 17"/></symbol>',
];

// Newt marks
const marks = [
  `<symbol id="mark-small" viewBox="0 0 48 48">${mark('small')}</symbol>`,
  `<symbol id="mark" viewBox="0 0 48 48">${mark('mid')}</symbol>`,
  `<symbol id="mark-full" viewBox="0 0 48 48">${mark('full')}</symbol>`,
];

// QR code for the host lobby (error correction M, so a TV's glare doesn't break it)
const qrcode = require(path.join(NM, 'qrcode-generator'));
function qrSymbol(id, text) {
  const qr = qrcode(0, 'M');
  qr.addData(text);
  qr.make();
  const n = qr.getModuleCount();
  let d = '';
  for (let r = 0; r < n; r++) {
    for (let c = 0; c < n; c++) if (qr.isDark(r, c)) d += `M${c + 4} ${r + 4}h1v1h-1z`;
  }
  const size = n + 8; // four-module quiet zone, as the standard asks
  return `<symbol id="${id}" viewBox="0 0 ${size} ${size}"><rect width="${size}" height="${size}" style="fill:var(--qr-light)"/><path d="${d}" style="fill:var(--qr-dark)"/></symbol>`;
}
const qr = [qrSymbol('qr-482913', 'https://knewt.app/join/482913')];

const sprite = `<svg xmlns="http://www.w3.org/2000/svg" width="0" height="0" style="position:absolute" aria-hidden="true" focusable="false">${[...lucide, ...custom, ...marks, ...qr].join('')}</svg>`;
const js = `// GENERATED by build-assets.js. Lucide icons (ISC, see icons/LICENSE-lucide.txt), custom glyphs, the newt mark and the lobby QR code.
document.currentScript.insertAdjacentHTML('afterend', ${JSON.stringify(sprite)});
`;
fs.writeFileSync(path.join(__dirname, 'sprite.js'), js);
fs.copyFileSync(path.join(NM, 'lucide-static', 'LICENSE'), path.join(__dirname, 'icons', 'LICENSE-lucide.txt'));
fs.writeFileSync(path.join(__dirname, 'icons', 'mark.svg'), `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 48 48" style="--mark-body:#E55F29;--mark-eye:#1D1A16;--mark-dot:#1D1A16">${mark('full')}</svg>\n`);
console.log('wrote sprite.js', js.length, 'bytes;', LUCIDE.length, 'Lucide icons');
