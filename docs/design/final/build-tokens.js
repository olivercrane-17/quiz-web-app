// Writes ../tokens.css from tokens.js. Run: node build-tokens.js
'use strict';
const fs = require('fs');
const path = require('path');
const T = require('./tokens.js');

const decl = (obj, prefix = '--kn-') => Object.entries(obj).map(([k, v]) => `  ${prefix}${k}: ${v};`).join('\n');
const block = (sel, body) => `${sel} {\n${body}\n}\n`;
const indent = (s) => s.split('\n').map((l) => (l ? '  ' + l : l)).join('\n');

const staticTokens = [
  `  --kn-font-display: ${T.fonts.display};`,
  `  --kn-font-text: ${T.fonts.text};`,
  `  --kn-font-emoji: ${T.fonts.emoji};`,
  ...Object.entries(T.type).flatMap(([k, [size, lh, wght, face, track]]) => [
    `  --kn-text-${k}: ${size};`,
    `  --kn-text-${k}--line-height: ${lh};`,
    `  --kn-text-${k}--font-weight: ${wght};`,
    `  --kn-text-${k}--letter-spacing: ${track};`,
    `  --kn-text-${k}--font-family: var(--kn-font-${face});`,
  ]),
  decl(Object.fromEntries(Object.entries(T.radius).map(([k, v]) => ['radius-' + k, v]))),
  decl(T.space),
  decl(T.elevation),
  decl(T.motion),
  decl(Object.fromEntries(Object.entries(T.z).map(([k, v]) => ['z-' + k, v]))),
  decl(T.layout),
  '  --kn-motion-distance: 1; /* multiply every translate by this; 0 under reduced motion */',
  '  --kn-reading-tracking: 0em;',
  '  --kn-reading-leading: 1.5;',
].join('\n');

const themeBody = (colors, extras, scheme) => `  color-scheme: ${scheme};\n${decl(colors)}\n${decl(extras)}`;

const colorNames = Object.keys(T.light);
const twColors = colorNames.map((k) => `  --color-${k}: var(--kn-${k});`).join('\n');
const twType = Object.keys(T.type).map((k) => [
  `  --text-${k}: var(--kn-text-${k});`,
  `  --text-${k}--line-height: var(--kn-text-${k}--line-height);`,
  `  --text-${k}--font-weight: var(--kn-text-${k}--font-weight);`,
  `  --text-${k}--letter-spacing: var(--kn-text-${k}--letter-spacing);`,
].join('\n')).join('\n');

const css = `/*
 * Knewt design tokens. GENERATED by docs/design/final/build-tokens.js from tokens.js: edit those, not this file.
 *
 * How to use
 *   Plain CSS: link this file and use var(--kn-*). The prototype in docs/design/final/ does exactly that.
 *   Tailwind v4: copy this file to src/app/tokens.css and import it right after Tailwind in globals.css:
 *       @import "tailwindcss";
 *       @import "./tokens.css";
 *     The @theme inline block at the bottom turns every token into utilities (bg-page, text-ink-2,
 *     border-rule-strong, text-display-3, rounded-xl, shadow-soft, ease-spring, max-w-play ...).
 *     "inline" makes each utility read the --kn-* variable where it is used, so a data-theme or
 *     data-feedback attribute on any element re-themes everything inside it.
 *
 * Switches (set on <html>; the app stores the player's choice and writes the attribute before first paint)
 *   data-theme="light" | "dark"     overrides prefers-color-scheme (absent = follow the system)
 *   data-feedback="contrast"        high-contrast feedback: correct and incorrect become blue and orange
 *   data-readable="on"              readable text: 0.05em tracking, 1.6 line height, plainer paper, no grain
 *   data-motion="reduce" | "full"   overrides prefers-reduced-motion either way
 *
 * Every colour pair is measured by docs/design/final/contrast.js (node contrast.js --check).
 */

/* 1. Static tokens: type, radius, spacing, elevation, motion, layers, layout */
${block(':root', staticTokens)}
/* 2. Light theme, the default */
${block(':root,\n[data-theme="light"]', themeBody(T.light, T.themeExtras.light, 'light'))}
/* 3. Dark theme: follows the system unless data-theme="light"; data-theme="dark" forces it */
@media (prefers-color-scheme: dark) {
${indent(block(':root:not([data-theme="light"])', themeBody(T.dark, T.themeExtras.dark, 'dark')))}}
${block('[data-theme="dark"]', themeBody(T.dark, T.themeExtras.dark, 'dark'))}
/* 4. High-contrast feedback (Settings). Blue means correct, orange means wrong; icons and words stay. */
${block('[data-feedback="contrast"]', decl(T.hcLight))}@media (prefers-color-scheme: dark) {
${indent(block(':root:not([data-theme="light"])[data-feedback="contrast"]', decl(T.hcDark)))}}
${block('[data-theme="dark"][data-feedback="contrast"]', decl(T.hcDark))}
/* 5. Readable text (Settings) */
${block('[data-readable="on"]', decl(T.readableLight) + '\n  --kn-reading-tracking: 0.05em;\n  --kn-reading-leading: 1.6;\n  --kn-grain-opacity: 0;')}@media (prefers-color-scheme: dark) {
${indent(block(':root:not([data-theme="light"])[data-readable="on"]', decl(T.readableDark)))}}
${block('[data-theme="dark"][data-readable="on"]', decl(T.readableDark))}
/* 6. Reduced motion: movement off, fades stay. data-motion overrides the OS either way. */
@media (prefers-reduced-motion: reduce) {
  :root:not([data-motion="full"]) {
    --kn-motion-distance: 0;
  }
}
[data-motion="reduce"] {
  --kn-motion-distance: 0;
}

/* 7. Forced colours: the system palette takes over; borders, icons and words carry every state */
@media (forced-colors: active) {
  :root {
    --kn-grain-opacity: 0;
  }
}

/*
 * 8. Tailwind v4: the dark: variant follows the same rule as the tokens (system, unless data-theme says otherwise).
 * Components rarely need it, because every colour token already switches by itself.
 */
@custom-variant dark {
  &:where([data-theme="dark"], [data-theme="dark"] *) {
    @slot;
  }
  @media (prefers-color-scheme: dark) {
    &:where(:root:not([data-theme="light"]), :root:not([data-theme="light"]) *) {
      @slot;
    }
  }
}

/*
 * 9. Tailwind v4 theme. Paste-ready: this block only references the variables above.
 * "--color-*: initial" removes Tailwind's default palette so nobody reaches for bg-red-500;
 * every colour in the product is one of these semantic tokens.
 */
@theme inline {
  --color-*: initial;
  --color-transparent: transparent;
  --color-current: currentColor;
${twColors}

  /* Aliases kept for the foundation code written before these tokens existed */
  --color-background: var(--kn-page);
  --color-foreground: var(--kn-ink);
  --color-muted: var(--kn-sunken);
  --color-muted-foreground: var(--kn-ink-3);
  --color-border: var(--kn-rule-strong);
  --color-ring: var(--kn-focus);

  --font-sans: var(--kn-font-text);
  --font-display: var(--kn-font-display);
  --font-text: var(--kn-font-text);
  --font-emoji: var(--kn-font-emoji);

${twType}

${Object.keys(T.radius).map((k) => `  --radius-${k}: var(--kn-radius-${k});`).join('\n')}

  --spacing-gutter: var(--kn-gutter);
  --spacing-tap: var(--kn-tap-min);
  --spacing-answer: var(--kn-answer-min);

  --shadow-soft: var(--kn-shadow-soft);
  --shadow-sheet: var(--kn-shadow-sheet);
  --shadow-pop: var(--kn-shadow-pop);
  --shadow-ledge: 0 var(--kn-ledge-2) 0 var(--kn-ledge);
  --shadow-ledge-pressed: 0 var(--kn-ledge-1) 0 var(--kn-ledge);

  --ease-out: var(--kn-ease-out);
  --ease-in-out: var(--kn-ease-in-out);
  --ease-spring: var(--kn-ease-spring);
  --ease-press: var(--kn-ease-press);
  --ease-exit: var(--kn-ease-exit);

  --container-play: var(--kn-container-play);
  --container-reading: var(--kn-container-reading);
  --container-page: var(--kn-container-page);

  --animate-stamp: kn-stamp var(--kn-dur-base) var(--kn-ease-spring) both;
  --animate-rise: kn-rise var(--kn-dur-reveal) var(--kn-ease-out) both;
  --animate-shake: kn-shake 300ms var(--kn-ease-in-out) both;
  --animate-fade: kn-fade var(--kn-dur-fade) linear both;

  @keyframes kn-stamp {
    from { opacity: 0; transform: scale(calc(1 + 0.4 * var(--kn-motion-distance))) rotate(calc(10deg * var(--kn-motion-distance))); }
    to { opacity: 1; transform: none; }
  }
  @keyframes kn-rise {
    from { opacity: 0; transform: translateY(calc(10px * var(--kn-motion-distance))); }
    to { opacity: 1; transform: none; }
  }
  @keyframes kn-shake {
    0%, 100% { transform: none; }
    25%, 75% { transform: translateX(calc(-6px * var(--kn-motion-distance))); }
    50% { transform: translateX(calc(6px * var(--kn-motion-distance))); }
  }
  @keyframes kn-fade {
    from { opacity: 0; }
    to { opacity: 1; }
  }
}
`;

fs.writeFileSync(path.join(__dirname, '..', 'tokens.css'), css);
console.log('wrote', path.relative(process.cwd(), path.join(__dirname, '..', 'tokens.css')), css.length, 'bytes');
