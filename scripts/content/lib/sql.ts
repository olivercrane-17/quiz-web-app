/**
 * The non-secret SQL loads the content build commits (ARCHITECTURE §5.3,
 * §8.16): supabase/seed/answer-entities.sql, practice-items.sql and
 * config.sql. Each is idempotent upserts only, so it applies unattended
 * through MCP (01-ENGINEERING-CONSTRAINTS, "Supabase MCP confirmation
 * prompts"): no DELETE, DROP or TRUNCATE, and nothing a re-run changes.
 *
 * Statements stay well under the 400 kB a single MCP execute_sql call
 * takes (§5.4), so the orchestrator applies a file statement by statement.
 */

/** A SQL string literal. Standard-conforming strings: only ' needs doubling. */
export function sqlText(value: string): string {
  if (value.includes("\u0000")) throw new Error("NUL in a SQL literal");
  return `'${value.replaceAll("'", "''")}'`;
}

export function sqlInt(value: number): string {
  if (!Number.isSafeInteger(value)) throw new Error(`not an integer: ${value}`);
  return String(value);
}

export function sqlBool(value: boolean): string {
  return value ? "true" : "false";
}

/** A jsonb literal from a JSON value, with stable key order. */
export function sqlJson(value: unknown): string {
  return `${sqlText(JSON.stringify(sortKeys(value)))}::jsonb`;
}

function sortKeys(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(sortKeys);
  if (value !== null && typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value as Record<string, unknown>)
        .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
        .map(([key, inner]) => [key, sortKeys(inner)]),
    );
  }
  return value;
}

/** camelCase to snake_case: crowdMinN is crowd_min_n (§5.3). */
export function snakeCase(name: string): string {
  return name.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toLowerCase();
}

export const SEED_HEADER = (source: string, what: string) =>
  [
    `-- Generated by \`npm run content:build\` from ${source} (ARCHITECTURE §5.3).`,
    "-- Do not edit: CI rebuilds it and fails on any difference.",
    `-- ${what}`,
    "-- Idempotent upserts only, so it applies unattended through MCP execute_sql,",
    "-- one statement per call.",
    "",
  ].join("\n");

export interface EntityRow {
  answerType: string;
  entityId: string;
  display: string;
  optionLabel: string;
  active: boolean;
}

/**
 * private.answer_entities (§5.5, §8.3): every entry ever published, active
 * or not, so an old guess still resolves and displays. One statement per
 * answer type.
 */
export function answerEntitiesSql(
  groups: readonly { type: string; rows: readonly EntityRow[] }[],
): string {
  const parts = [
    SEED_HEADER(
      "content/answer-lists/",
      "Every published entry with its display, clue-4 option label and active flag (§5.5).",
    ),
  ];
  for (const { type, rows } of groups) {
    if (rows.length === 0) continue;
    parts.push(
      `-- ${type}: ${rows.length} entries`,
      "insert into private.answer_entities (answer_type, entity_id, display, option_label, active)",
      "values",
      rows
        .map(
          (row, index) =>
            `  (${sqlText(row.answerType)}, ${sqlText(row.entityId)}, ${sqlText(row.display)}, ${sqlText(row.optionLabel)}, ${sqlBool(row.active)})${index === rows.length - 1 ? "" : ","}`,
        )
        .join("\n"),
      "on conflict (answer_type, entity_id) do update",
      "  set display = excluded.display,",
      "      option_label = excluded.option_label,",
      "      active = excluded.active;",
      "",
    );
  }
  return parts.join("\n");
}

export interface CategoryRow {
  id: string;
  slug: string;
  name: string;
  shortName: string;
}

export interface PracticeRow {
  id: string;
  category: string;
  ord: number;
  optionCount: number;
}

/** One practice row exactly as practice-items.sql writes it, so the build can read the file back. */
const PRACTICE_ROW =
  /^ {2}\('((?:fx\.)?p\.[a-z]+\.\d{4})', '([a-z]+)', (\d+), ([2-4])\),?$/;

/**
 * The bit positions already handed out, read back from the committed
 * practice-items.sql. A position is a bit in every player's
 * practice_firsts row (§8.12), so it never moves and is never reused.
 */
export function readPracticeRows(sql: string | null): PracticeRow[] {
  if (sql === null) return [];
  const rows: PracticeRow[] = [];
  for (const line of sql.split("\n")) {
    const match = PRACTICE_ROW.exec(line);
    if (!match) continue;
    const [, id = "", category = "", ord = "0", options = "0"] = match;
    rows.push({ id, category, ord: Number(ord), optionCount: Number(options) });
  }
  return rows;
}

/**
 * private.categories and private.practice_items (§8.3). The categories go
 * first because practice_items references them. An existing item keeps
 * its `ord` in the database whatever the file says, and a new item whose
 * `ord` were taken would fail on the unique index, loudly.
 */
export function practiceItemsSql(
  categories: readonly CategoryRow[],
  rows: readonly PracticeRow[],
): string {
  const parts = [
    SEED_HEADER(
      "content/categories.json and content/practice/",
      "The categories, then every practice item ever shipped with its category, option count and bit position (§8.3, §8.12). Positions are append-only.",
    ),
    "insert into private.categories (id, slug, name, short_name)",
    "values",
    categories
      .map(
        (row, index) =>
          `  (${sqlText(row.id)}, ${sqlText(row.slug)}, ${sqlText(row.name)}, ${sqlText(row.shortName)})${index === categories.length - 1 ? "" : ","}`,
      )
      .join("\n"),
    "on conflict (id) do update",
    "  set slug = excluded.slug,",
    "      name = excluded.name,",
    "      short_name = excluded.short_name;",
    "",
  ];
  if (rows.length > 0) {
    parts.push(
      `-- ${rows.length} practice items, by bit position`,
      "insert into private.practice_items (id, category, ord, option_count)",
      "values",
      rows
        .map(
          (row, index) =>
            `  (${sqlText(row.id)}, ${sqlText(row.category)}, ${sqlInt(row.ord)}, ${sqlInt(row.optionCount)})${index === rows.length - 1 ? "" : ","}`,
        )
        .join("\n"),
      "on conflict (id) do update",
      "  set category = excluded.category,",
      "      option_count = excluded.option_count;",
      "",
    );
  }
  return parts.join("\n");
}

/**
 * private.config from src/config/shared.json (§5.3): crowd_min_n,
 * percentile_min_n and the rest, so the client and SQL agree.
 */
export function configSql(shared: Record<string, unknown>): string {
  const entries = Object.entries(shared)
    .filter(([key]) => !key.startsWith("$"))
    .map(([key, value]) => [snakeCase(key), value] as const)
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  return [
    SEED_HEADER(
      "src/config/shared.json",
      "The values the client and SQL must agree on (§5.3), keyed in snake_case.",
    ),
    "insert into private.config as c (key, value)",
    "values",
    entries
      .map(
        ([key, value], index) =>
          `  (${sqlText(key)}, ${sqlJson(value)})${index === entries.length - 1 ? "" : ","}`,
      )
      .join("\n"),
    "on conflict (key) do update",
    "  set value = excluded.value,",
    "      updated_at = private.now();",
    "",
  ].join("\n");
}
