/**
 * Icons (DESIGN §5): Lucide's shapes on its 24 px grid, round caps and
 * joins, drawn here as tiny components so only the icons a screen uses
 * ship with it and no icon package is needed. Lucide is ISC licensed (some
 * shapes derive from Feather, MIT); the notice is in ./LICENSE-lucide.txt
 * and belongs on /credits. The tally glyph is our own, drawn on Lucide's
 * rules.
 *
 * Every icon is decorative: the word beside it carries the meaning, so it
 * is hidden from assistive technology, and an icon-only button names itself
 * with `aria-label`. Small icons get a heavier stroke so they keep their
 * weight: 2 at 19 px and up, 2.3 from 15 px, 2.8 below.
 */
import type { ReactNode } from "react";

import { cx } from "./cx";

export interface IconProps {
  className?: string;
  /** Pixels; 20 by default. */
  size?: number;
}

/** DESIGN §5: the stroke thickens as the icon shrinks. */
export function iconStroke(size: number): number {
  if (size >= 19) return 2;
  if (size >= 15) return 2.3;
  return 2.8;
}

function Icon({
  className,
  size = 20,
  filled = false,
  children,
}: IconProps & { filled?: boolean; children: ReactNode }) {
  return (
    <svg
      aria-hidden="true"
      focusable="false"
      viewBox="0 0 24 24"
      width={size}
      height={size}
      fill={filled ? "currentColor" : "none"}
      stroke="currentColor"
      strokeWidth={iconStroke(size)}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={cx("shrink-0", className)}
    >
      {children}
    </svg>
  );
}

