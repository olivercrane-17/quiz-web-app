/**
 * Batch incidents (CONTENT_GUIDE §9.6, §11.3). A fabricated source fails the
 * whole batch: the editor rejects it, fresh checkers re-check every item in
 * it, and the incident goes in the register.
 *
 * `content:batch -- incident --kind fabricated_source` therefore voids the
 * A, B and T records of every item that is not yet active (a voided checking
 * item goes back to draft, keeping its estimate, since the item itself did
 * not change), and stores everyone who had checked an item of the batch in
 * the incident's `checkers`. content:record refuses those checkers for the
 * batch from then on. Items already active cannot be re-checked in place;
 * they are listed for the editor's re-check under §9.10.
 *
 * `--kind invalid_check` is narrower and reaches further: one checker's
 * records were not real checks (generated by script, say), so that checker's
 * A, B and T records are voided on every item of the batch, active ones
 * included. An active item loses its accept, which rested on them, and goes
 * back to checking for a fresh run of that pass and a new decision. The
 * incident's `checkers` holds that one checker, whom content:record refuses
 * for the batch from then on.
 */
import type { AnyItem } from "../schema/items.ts";
import type { CheckRecord } from "../schema/verification.ts";
import type { Bank } from "./bank.ts";
import { cloneJson } from "./json.ts";
import { batchItems, sameAgentRun } from "./register.ts";
import { editableCopy } from "./store.ts";

export interface VoidedChecks {
  /** Items whose checks were voided, ready for saveItems. */
  updates: Map<string, AnyItem>;
  /** Every checker of an item of the batch, active items included. */
  checkers: string[];
  /** Active items: they keep their checks and need a §9.10 re-check. */
  active: string[];
}

export function voidBatchChecks(bank: Bank, batchId: string): VoidedChecks {
  const updates = new Map<string, AnyItem>();
  const checkers = new Set<string>();
  const active: string[] = [];
  for (const record of batchItems(bank, batchId)) {
    const item = record.item;
    const v = item.verification;
    const records = [
      ...(v?.checks ?? []),
      ...(v?.tiebreak ? [v.tiebreak] : []),
    ];
    for (const check of records) checkers.add(check.checker);
    if (item.status === "active") {
      active.push(record.id);
      continue;
    }
    if (item.status !== "draft" && item.status !== "checking") continue;
    if (!v || records.length === 0) continue;
    const next = cloneJson(item);
    if (next.verification) {
      next.verification.checks = [];
      next.verification.tiebreak = null;
    }
    if (next.status === "checking") next.status = "draft";
    updates.set(record.id, next);
  }
  return { updates, checkers: [...checkers].sort(), active };
}

/** The A, B and T records `checker` made on an item (run ids compared). */
export function recordsBy(item: AnyItem, checker: string): CheckRecord[] {
  const v = item.verification;
  return [...(v?.checks ?? []), ...(v?.tiebreak ? [v.tiebreak] : [])].filter(
    (check) => sameAgentRun(check.checker, checker),
  );
}

export interface VoidedCheckerRecords {
  /** Items that lost a record, ready for saveItems. */
  updates: Map<string, AnyItem>;
  /** Items that were active: their accept no longer stands. */
  reopened: string[];
  /** A, B and T records removed, across the batch. */
  voided: number;
}

/**
 * Voids one checker's A, B and T records on every item of a batch (an
 * invalid_check incident). Each affected item changes only where it must:
 * the checker's records go (a tiebreak becomes null), and
 * - an active item goes back to checking when it still carries its
 *   estimate and a check, otherwise to draft, and loses verification.editor,
 *   since the accept rested on the voided records;
 * - a checking item left with no check goes back to draft;
 * - a draft stays draft.
 * Cut and retired items keep their history untouched.
 */
export function voidCheckerRecords(
  bank: Bank,
  batchId: string,
  checker: string,
): VoidedCheckerRecords {
  const updates = new Map<string, AnyItem>();
  const reopened: string[] = [];
  let voided = 0;
  for (const record of batchItems(bank, batchId)) {
    const item = record.item;
    if (item.status === "cut" || item.status === "retired") continue;
    const mine = recordsBy(item, checker).length;
    if (mine === 0) continue;
    const next = editableCopy(record);
    const v = next.verification;
    if (!v) continue;
    voided += mine;
    v.checks = v.checks.filter(
      (check) => !sameAgentRun(check.checker, checker),
    );
    if (v.tiebreak && sameAgentRun(v.tiebreak.checker, checker))
      v.tiebreak = null;
    if (next.status === "active") {
      delete v.editor;
      const estimated = "predicted" in next && next.predicted !== undefined;
      next.status = estimated && v.checks.length > 0 ? "checking" : "draft";
      reopened.push(record.id);
    } else if (next.status === "checking" && v.checks.length === 0) {
      next.status = "draft";
    }
    updates.set(record.id, next);
  }
  return { updates, reopened, voided };
}
